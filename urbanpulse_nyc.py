import requests
import pandas as pd

url = "https://data.cityofnewyork.us/resource/erm2-nwe9.json"

params = {
    "$select": "unique_key,created_date,closed_date,agency,complaint_type,descriptor,borough,status,latitude,longitude",
    "$limit": 1000,
    "$order": "created_date DESC"
}

# Send a request to the NYC 311 API and receive the response
response = requests.get(url, params=params, timeout=60)

# Display the HTTP status code (200 means success)
print("Status Code:", response.status_code)

# Raise an error if the request fails
response.raise_for_status()

# Convert the API response from JSON to Python data
data = response.json()

# Convert the data into a Pandas DataFrame
df = pd.DataFrame(data)

# Display the total number of records (rows)
print("Total Records:", len(df))

# Display the total number of columns
print("Total Columns:", len(df.columns))

# Display the first 5 rows of the dataset
df.head()

# Display column names and data types to understand the dataset structure
print("Column Names:")
print(df.columns.tolist())

print("\nData Types:")
print(df.dtypes)

# Count missing values in each column
print(df.isnull().sum())

# Count duplicate request IDs
print("Duplicate IDs:", df["unique_key"].duplicated().sum())

# Convert date columns to datetime format
df["created_date"] = pd.to_datetime(df["created_date"], errors="coerce")
df["closed_date"] = pd.to_datetime(df["closed_date"], errors="coerce")

# Display the updated data types
print(df[["created_date", "closed_date"]].dtypes)

print("Rows and Columns:", df.shape)
print("Total Records:", len(df))
print("\nMissing Values:")
print(df.isnull().sum())

# Analyze the distribution of complaint statuses
df["status"].value_counts()

# Extract NYC 311 records using API pagination

page_size = 10000
target_records = 100000
offset = 0

all_records = []

while offset < target_records:

    page_params = params.copy()
    page_params["$limit"] = min(page_size, target_records - offset)
    page_params["$offset"] = offset
    page_params["$order"] = "created_date DESC, unique_key DESC"

    response = requests.get(url, params=page_params, timeout=60)
    response.raise_for_status()

    batch = response.json()

    if not batch:
        break

    all_records.extend(batch)

    print("Records fetched:", len(all_records))

    offset += len(batch)

    if len(batch) < page_params["$limit"]:
        break

# Create the raw DataFrame
df_raw = pd.DataFrame(all_records)

print("\nTotal Records:", len(df_raw))
print("Rows and Columns:", df_raw.shape)